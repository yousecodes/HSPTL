"""Typed in-process ports. Adapters are modules in the monolith, not services."""
from __future__ import annotations

from typing import Any, Protocol


class TerminologyPortContract(Protocol):
    def lookup(self, term: str) -> dict[str, Any]: ...
    def query_ecl(self, expression: str) -> dict[str, Any]: ...


class SnowstormECLPort(Protocol):
    def expand(self, expression: str) -> dict[str, Any]: ...


class StandardsExportPort(Protocol):
    def to_fhir_observation(self, observation: dict[str, Any]) -> dict[str, Any]: ...
    def export_cql(self, rule_id: str, expression: str) -> dict[str, Any]: ...
    def cds_hooks_descriptor(self, service_id: str, title: str, hook: str) -> dict[str, Any]: ...


class InteropPort(Protocol):
    def lti_13_descriptor(self, issuer: str, client_id: str, deployment_id: str) -> dict[str, Any]: ...
    def xapi_statement(self, actor: dict[str, Any], verb: str, activity: dict[str, Any],
                       result: dict[str, Any] | None = None) -> dict[str, Any]: ...
    def scorm_runtime_data(self, completion: str, success: str | None = None,
                           score: float | None = None) -> dict[str, str]: ...
